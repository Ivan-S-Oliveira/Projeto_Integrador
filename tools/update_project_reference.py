# Characters that some readers treat as line breaks. They are shown as visible
# placeholders, so every reader counts the same lines.
LINE_SEPARATORS_RE = re.compile("[\x0b\x0c\x1c\x1d\x1e\x85\u2028\u2029]")
RENDERED_BODIES = {}


def normalize_text(text):
    """CRLF and CR become LF; other line separators become visible placeholders."""
    if text is None:
        return text
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return LINE_SEPARATORS_RE.sub(lambda m: f"⟨U+{ord(m.group(0)):04X}⟩", text)


def split_lines(text):
    """Lines of a normalised text, like str.splitlines() but only on LF."""
    text = normalize_text(text or "")
    if not text:
        return []
    lines = text.split("\n")
    if lines[-1] == "":
        lines.pop()
    return lines


def first_purpose(rel, text, analysis=None):
    """One-line purpose of a file: module docstring, first heading or first comment."""
    if analysis is not None and getattr(analysis, "docstring", ""):
        return analysis.docstring.strip().splitlines()[0][:160]
    if analysis is not None and getattr(analysis, "headings", None):
        return analysis.headings[0][:160]
    for line in split_lines(text or "")[:20]:
        stripped = line.strip()
        if not stripped:
            continue
        heading = re.match(r"^#{1,6}\s+(.+)$", stripped)
        if heading and rel.suffix.lower() in {".md", ".markdown", ".rst", ".mdown", ".mkd"}:
            return heading.group(1)[:160]
        comment = re.match(r'^(?:#+|//|--|;|rem\b|::)\s*(.+)$', stripped, re.IGNORECASE)
        if comment and not stripped.startswith("#!"):
            return comment.group(1)[:160]
        if rel.suffix.lower() in {".md", ".markdown", ".rst"}:
            return stripped[:160]
        break
    return ""


