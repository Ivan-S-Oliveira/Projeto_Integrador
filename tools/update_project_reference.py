def _join_text(value):
    if isinstance(value, list):
        return "".join(str(v) for v in value)
    return "" if value is None else str(value)


def render_output(output, *, cell_number, out_index, opts, redactor):
    """Render one notebook output. Returns (markdown_blocks, structured, events)."""
    kind = output.get("output_type", "unknown")
    blocks = []
    events = []
    structured = {"output_type": kind}
    count = output.get("execution_count")
    if count is not None:
        structured["execution_count"] = count
    title = f"**Output {out_index} of Cell {cell_number} ({kind}"
    title += f", Out[{count}]" if count is not None else ""

    def text_block(text, lexer):
        text = normalize_text(ANSI_RE.sub("", text))
        text, found = redactor(text)
        for event in found:
            event["detail"] += f" (cell {cell_number}, output {out_index})"
        events.extend(found)
        return code_block(text.rstrip("\n"), lexer), text

    if kind == "stream":
        name = str(output.get("name", "stdout"))
        block, text = text_block(_join_text(output.get("text")), "text")
        blocks.extend([title + f", {name})**", "", block])
        structured.update({"name": name, "text": text})
    elif kind == "error":
        trace = "\n".join(_join_text(line) for line in output.get("traceback", ()))
        raw = f"{output.get('ename', '')}: {output.get('evalue', '')}\n{trace}"
        block, text = text_block(raw, "text")
        blocks.extend([title + ")**", "", block])
        structured.update({"ename": output.get("ename"), "evalue": output.get("evalue"), "text": text})
    elif kind in {"execute_result", "display_data", "update_display_data"}:
        data = output.get("data", {}) or {}
        blocks.append(title + ", mime types: " + ", ".join(f"`{m}`" for m in data) + ")**")
        structured["data"] = {}
        for mime, value in data.items():
            if mime == "text/html" and "text/plain" in data:
                # The same output is already shown as text/plain (e.g. DataFrames).
                blocks.extend(["", "`text/html` — omitted: the same output is shown in this output as text/plain"])
                structured["data"][mime] = "omitted (duplicate of text/plain)"
                continue
            if mime in TEXT_MIME_LEXER or mime.startswith("text/"):
                block, text = text_block(_join_text(value), TEXT_MIME_LEXER.get(mime, "text"))
                blocks.extend(["", f"`{mime}`", "", block])
                structured["data"][mime] = text
            elif mime.endswith("json"):
                raw = json.dumps(value, ensure_ascii=False, indent=2, default=str)
                block, text = text_block(raw, "json")
                blocks.extend(["", f"`{mime}`", "", block])
                structured["data"][mime] = value
            else:
                # Images and other binary payloads are not textual: never decoded.
                blocks.extend(["", f"`{mime}` — non-textual output omitted"])
                structured["data"][mime] = "omitted (non-textual)"
        metadata = output.get("metadata")
        if metadata:
            blocks.extend(["", "Output metadata:", "",
                           code_block(json.dumps(metadata, ensure_ascii=False, indent=2, default=str), "json")])
            structured["metadata"] = metadata
    else:
        raw = json.dumps(output, ensure_ascii=False, indent=2, default=str)
        block, text = text_block(raw, "json")
        blocks.extend([title + ")**", "", block])
        structured["raw"] = output
    return blocks, structured, events


def notebook_source_markdown(nb, analysis, *, opts, redactor, numbered):
    """Markdown of a notebook plus structured cells and redaction events."""
    order_note = " — **executed out of order**" if analysis.out_of_order else ""
    outputs_note = "all textual outputs included, never truncated"
    meta = nb.get("metadata", {}) or {}
    parts = [
        f"- Cells: `{analysis.cells}` (`{analysis.code_cells}` code, `{analysis.markdown_cells}` markdown)",
        f"- Code cells executed: `{analysis.executed_cells}` of `{analysis.code_cells}`{order_note}",
        f"- Kernel: `{analysis.kernel.get('display_name', '')}`; Python `{analysis.language_version}`",
        f"- nbformat: `{nb.get('nbformat')}.{nb.get('nbformat_minor')}`",
        f"- Outputs: `{outputs_note}`; images and binary outputs omitted",
        f"- Refer to a cell as `{analysis.path}#cell-N` (N = cell number below)",
        "- This is a readable rendering of the notebook (cells and saved outputs), not its raw JSON.",
        "",
        "Notebook metadata:",
        "",
        code_block(json.dumps(meta, ensure_ascii=False, indent=2, default=str), "json"),
        "",
    ]
    cells = []
    events = []
    for number, cell in enumerate(nb.get("cells", ()), 1):
        kind = cell.get("cell_type", "unknown")
        raw_source = cell_source(cell)
        source, found = redactor(raw_source.rstrip("\n"), mode="python" if kind == "code" else "prose")
        for event in found:
            event["detail"] += f" (cell {number}, source line {event['line']})"
        events.extend(found)
        shown = source
        cell_id = cell.get("id")
        id_note = f" · id `{cell_id}`" if cell_id else ""
        record = {"index": number, "id": cell_id, "cell_type": kind, "source": source,
                  "metadata": cell.get("metadata", {}) or {}}
        if kind == "code":
            count = cell.get("execution_count")
            record["execution_count"] = count
            shown_count = count if count is not None else " "
            parts.append(f"### Cell {number} [code] · In [{shown_count}] · notebook `{analysis.path}`{id_note}")
        else:
            parts.append(f"### Cell {number} [{kind}] · notebook `{analysis.path}`{id_note}")
        parts.append("")
        if record["metadata"]:
            parts.append("Cell metadata: `" + json.dumps(record["metadata"], ensure_ascii=False,
                                                        default=str).replace("`", "'") + "`")
            parts.append("")
        parts.append(code_block(shown, "python" if kind == "code" else "markdown"))
        if kind == "code":
            record["outputs"] = []
            for out_index, output in enumerate(cell.get("outputs", ()), 1):
                blocks, structured, found = render_output(
                    output, cell_number=number, out_index=out_index, opts=opts, redactor=redactor,
                )
                events.extend(found)
                record["outputs"].append(structured)
                parts.append("")
                parts.extend(blocks)
        attachments = cell.get("attachments")
        if attachments:
            names = ", ".join(f"`{name}`" for name in attachments)
            parts.extend(["", f"Attachments: {names} (non-textual, omitted)"])
            record["attachments"] = sorted(attachments)
        parts.append("")
        cells.append(record)
    return "\n".join(parts).rstrip(), cells, events


