def heading_lines(text):
    """Level-2 headings outside file blocks and code fences -> 1-based line number."""
    found = {}
    for number, (line, inside) in enumerate(iter_structure(text), 1):
        if not inside and line.startswith("## "):
            found.setdefault(line[3:].strip(), number)
    return found


def section_sizes(text):
    """Bytes of every numbered level-2 section (headings outside file blocks)."""
    sizes = {}
    current = "Header and instructions"
    for line, protected in iter_structure(text):
        if not protected and re.match(r"^## \d+\. ", line):
            current = line[3:].strip()
        sizes[current] = sizes.get(current, 0) + len(line.encode("utf-8"))
    return sizes


