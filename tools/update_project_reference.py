DEF_NODES = (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)


def nested_symbols(node, *, path, module, text, prefix, nested=True):
    """Symbols defined inside `node` (functions in functions, classes in
    functions or classes, definitions under if/try/with/for)."""
    found = []
    for child in ast.iter_child_nodes(node):
        if isinstance(child, DEF_NODES):
            symbol = extract_symbol(child, path=path, module=module, text=text, parent=prefix)
            if nested:
                symbol.kind = "nested_class" if isinstance(child, ast.ClassDef) else "nested_function"
            found.append(symbol)
            child_prefix = f"{prefix}.{child.name}" if prefix else child.name
            found.extend(nested_symbols(child, path=path, module=module, text=text,
                                        prefix=child_prefix, nested=True))
        else:
            found.extend(nested_symbols(child, path=path, module=module, text=text,
                                        prefix=prefix, nested=nested))
    return found


def analyze_python(path, text, internal_roots):
    module = module_name(path)
    lines = len(text.splitlines())
    try:
        tree = ast.parse(text, filename=path.as_posix())
    except SyntaxError as exc:
        return PythonFileAnalysis(
            path=path.as_posix(), module=module, docstring="", parse_error=str(exc),
            imports=[], internal_imports=[], external_imports=[], import_from=[],
            calls=[], call_sites=[], symbols=[], top_level_names=[], constants={},
            env_vars=env_names(text), file_literals=file_literals(text), lines=lines,
        )
    imports, froms, star = imported_names(tree)
    internal = sorted(
        v for v in imports if v.split(".")[0] in internal_roots or v.startswith(".")
    )
    external = sorted(set(imports) - set(internal))
    symbols = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            symbols.append(extract_symbol(node, path=path, module=module, text=text))
            symbols.extend(nested_symbols(node, path=path, module=module, text=text, prefix=node.name))
        elif isinstance(node, ast.ClassDef):
            symbols.append(extract_symbol(node, path=path, module=module, text=text))
            for child in node.body:
                if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    symbols.append(
                        extract_symbol(child, path=path, module=module, text=text, parent=node.name)
                    )
                    symbols.extend(nested_symbols(child, path=path, module=module, text=text,
                                                  prefix=f"{node.name}.{child.name}"))
                elif isinstance(child, ast.ClassDef):
                    inner = extract_symbol(child, path=path, module=module, text=text, parent=node.name)
                    inner.kind = "nested_class"
                    symbols.append(inner)
                    symbols.extend(nested_symbols(child, path=path, module=module, text=text,
                                                  prefix=f"{node.name}.{child.name}"))
        elif isinstance(node, (ast.If, ast.Try, ast.With, ast.For, ast.While)):
            # Module-level definitions under if/try (e.g. try/except ImportError).
            symbols.extend(nested_symbols(node, path=path, module=module, text=text,
                                          prefix="", nested=False))
    return PythonFileAnalysis(
        path=path.as_posix(),
        module=module,
        docstring=(ast.get_docstring(tree) or "").strip(),
        parse_error=None,
        imports=imports,
        internal_imports=internal,
        external_imports=external,
        import_from=froms,
        calls=call_names(tree),
        call_sites=call_sites(tree, path.as_posix()),
        symbols=symbols,
        top_level_names=top_level_names(tree),
        constants=assigned_constants(tree),
        env_vars=env_names(text),
        file_literals=file_literals(text),
        has_star_import=star,
        lines=lines,
        module_aliases=module_aliases(tree),
        references=referenced_names(tree),
    )


