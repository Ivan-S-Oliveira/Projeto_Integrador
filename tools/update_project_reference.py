def module_name(path):
    """Dotted module name. Leading dots of folders (e.g. `.scripts`) are dropped."""
    parts = [part.lstrip(".") or part for part in path.with_suffix("").parts]
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


