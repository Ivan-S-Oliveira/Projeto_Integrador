def walk_inventory(root, tracked, untracked, max_entries=0):
    """Every file of the working folder. Tooling folders are pruned unless Git
    tracks files inside them. Returns (rows, truncated, pruned_dirs)."""
    tracked_dirs = set()
    for value in tracked:
        parts = Path(value).parts
        for size in range(1, len(parts)):
            tracked_dirs.add("/".join(parts[:size]))
    rows = []
    pruned = []
    for current, dirs, files in os.walk(root):
        rel_dir = Path(current).relative_to(root).as_posix()
        kept = []
        for name in sorted(dirs):
            rel = name if rel_dir == "." else f"{rel_dir}/{name}"
            if name in EXCLUDED_DIRS_ANYWHERE and rel not in tracked_dirs:
                pruned.append(rel)
                continue
            kept.append(name)
        dirs[:] = kept
        for name in sorted(files):
            absolute = Path(current) / name
            rel = absolute.relative_to(root).as_posix()
            try:
                stat = absolute.stat()
            except OSError:
                continue
            if rel in tracked:
                state = "tracked"
            elif rel in untracked:
                state = "untracked"
            else:
                state = "ignored"
            modified = datetime.fromtimestamp(stat.st_mtime, timezone.utc)
            rows.append(
                {
                    "path": rel,
                    "git": state,
                    "bytes": stat.st_size,
                    "modified_utc": modified.strftime("%Y-%m-%d %H:%M:%S"),
                }
            )
            if max_entries and len(rows) >= max_entries:
                return rows, True, pruned
    return rows, False, pruned


def last_commits(root):
    """Path -> last commit touching it (one `git log` call)."""
    output = git(
        root, "log", "--date=iso-strict", "--format=@@@%H|%ad|%an|%s", "--name-only",
        check=False,
    )
    result = {}
    current = None
    for line in output.splitlines():
        if line.startswith("@@@"):
            pieces = line[3:].split("|", 3)
            while len(pieces) < 4:
                pieces.append("")
            current = {"commit": pieces[0][:12], "date": pieces[1], "author": pieces[2],
                       "subject": pieces[3]}
        elif line.strip() and current is not None:
            result.setdefault(line.strip(), current)
    return result


