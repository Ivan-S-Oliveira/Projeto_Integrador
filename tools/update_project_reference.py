def _local(tag):
    return tag.rsplit("}", 1)[-1]


def _paragraph_text(element):
    pieces = []
    for node in element.iter():
        tag = _local(node.tag)
        if tag == "t" and node.text:
            pieces.append(node.text)
        elif tag == "tab":
            pieces.append("\t")
        elif tag in {"br", "cr"}:
            pieces.append("\n")
    return "".join(pieces)


def _docx_blocks(element, out):
    for child in element:
        tag = _local(child.tag)
        if tag == "p":
            text = _paragraph_text(child)
            if text.strip():
                out.append(text)
        elif tag == "tbl":
            out.append("[table]")
            for row in child:
                if _local(row.tag) != "tr":
                    continue
                cells = []
                for cell in row:
                    if _local(cell.tag) != "tc":
                        continue
                    inner = []
                    _docx_blocks(cell, inner)
                    cells.append(" / ".join(t.replace("\n", " ") for t in inner))
                out.append("| " + " | ".join(cells) + " |")
            out.append("[/table]")
        else:
            _docx_blocks(child, out)


def _natural_key(name):
    numbers = re.findall(r"\d+", name)
    return (int(numbers[-1]) if numbers else 0, name)


def docx_text(archive):
    names = set(archive.namelist())
    sections = []
    groups = [("body", ["word/document.xml"])]
    groups.append(("header", sorted((n for n in names if re.match(r"word/header\d*\.xml$", n)), key=_natural_key)))
    groups.append(("footer", sorted((n for n in names if re.match(r"word/footer\d*\.xml$", n)), key=_natural_key)))
    for label, name in (("footnotes", "word/footnotes.xml"), ("endnotes", "word/endnotes.xml"),
                        ("comments", "word/comments.xml")):
        groups.append((label, [name]))
    for label, members in groups:
        for member in members:
            if member not in names:
                continue
            out = []
            _docx_blocks(ET.fromstring(archive.read(member)), out)
            if out:
                sections.append(f"=== {label}: {member} ===")
                sections.extend(out)
    return "\n".join(sections)


def _relationship_targets(archive, rels_name, base_dir):
    if rels_name not in archive.namelist():
        return {}
    targets = {}
    for rel in ET.fromstring(archive.read(rels_name)):
        target = rel.get("Target", "")
        if target.startswith("/"):
            resolved = target.lstrip("/")  # absolute part name inside the package
        else:
            resolved = os.path.normpath(os.path.join(base_dir, target)).replace("\\", "/")
        targets[rel.get("Id")] = (rel.get("Type", ""), resolved)
    return targets


def pptx_text(archive):
    names = set(archive.namelist())
    slides = sorted((n for n in names if re.match(r"ppt/slides/slide\d+\.xml$", n)), key=_natural_key)
    out = []
    for index, slide in enumerate(slides, 1):
        out.append(f"--- slide {index} ({slide}) ---")
        root = ET.fromstring(archive.read(slide))
        for paragraph in root.iter():
            if _local(paragraph.tag) == "p":
                text = _paragraph_text(paragraph).strip()
                if text:
                    out.append(text)
        rels = _relationship_targets(archive, f"ppt/slides/_rels/{slide.rsplit('/', 1)[-1]}.rels", "ppt/slides")
        for rel_type, target in rels.values():
            if rel_type.endswith("/notesSlide") and target in names:
                notes = []
                for paragraph in ET.fromstring(archive.read(target)).iter():
                    if _local(paragraph.tag) == "p":
                        text = _paragraph_text(paragraph).strip()
                        if text and not text.isdigit():
                            notes.append(text)
                if notes:
                    out.append("[speaker notes]")
                    out.extend(notes)
    return "\n".join(out)


def xlsx_text(archive):
    """Every cell value and formula of every sheet, using only the stdlib."""
    names = set(archive.namelist())
    shared = []
    if "xl/sharedStrings.xml" in names:
        for item in ET.fromstring(archive.read("xl/sharedStrings.xml")):
            if _local(item.tag) == "si":
                shared.append("".join(n.text or "" for n in item.iter() if _local(n.tag) == "t"))
    rels = _relationship_targets(archive, "xl/_rels/workbook.xml.rels", "xl")
    workbook = ET.fromstring(archive.read("xl/workbook.xml"))
    out = []
    for node in workbook.iter():
        if _local(node.tag) == "definedName":
            out.append(f"[defined name] {node.get('name')} = {node.text}")
    for node in workbook.iter():
        if _local(node.tag) != "sheet":
            continue
        sheet_name = node.get("name")
        rel_id = next((v for k, v in node.attrib.items() if k.endswith("}id")), None)
        target = rels.get(rel_id, ("", ""))[1]
        state = node.get("state", "visible")
        out.append(f"=== sheet: {sheet_name} ({target}, {state}) ===")
        if target not in names:
            out.append("[sheet part not found]")
            continue
        count = 0
        for cell in ET.fromstring(archive.read(target)).iter():
            if _local(cell.tag) != "c":
                continue
            ref = cell.get("r", "?")
            cell_type = cell.get("t", "n")
            formula = value = None
            for child in cell:
                tag = _local(child.tag)
                if tag == "f":
                    formula = child.text or ""
                elif tag == "v":
                    value = child.text
                elif tag == "is":
                    value = "".join(n.text or "" for n in child.iter() if _local(n.tag) == "t")
            if cell_type == "s" and value is not None:
                try:
                    value = shared[int(value)]
                except (ValueError, IndexError):
                    pass
            elif cell_type == "b" and value is not None:
                value = "TRUE" if value == "1" else "FALSE"
            if value is None and formula is None:
                continue
            count += 1
            line = f"{sheet_name}!{ref}\t{'' if value is None else value}"
            if formula is not None:
                line += f"\t[formula] ={formula}"
            out.append(line)
        out.append(f"[{count} non-empty cells]")
    return "\n".join(out)


def pdf_text(data):
    try:
        from pypdf import PdfReader  # type: ignore
    except Exception:
        return None, "pypdf is not installed (pip install pypdf)"
    try:
        reader = PdfReader(io.BytesIO(data))
        out = []
        info = reader.metadata or {}
        for key, value in dict(info).items():
            out.append(f"[metadata] {key}: {value}")
        for index, page in enumerate(reader.pages, 1):
            out.append(f"--- page {index} ---")
            out.append((page.extract_text() or "").rstrip())
        return "\n".join(out), None
    except Exception as exc:
        return None, f"PDF extraction failed: {exc!r}"


def extract_document(data, suffix):
    """Return (text, error) for Office and PDF files."""
    if suffix == ".pdf":
        return pdf_text(data)
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            if suffix in {".docx", ".docm"}:
                return docx_text(archive), None
            if suffix in {".pptx", ".pptm"}:
                return pptx_text(archive), None
            return xlsx_text(archive), None
    except Exception as exc:
        return None, f"extraction failed: {exc!r}"


def _stat_value(value):
    if isinstance(value, bytes):
        try:
            return value.decode("utf-8")
        except UnicodeDecodeError:
            return value.hex()
    return value


def parquet_description(path):
    """Return (text, structured, error). Never reads data rows."""
    try:
        import pyarrow.parquet as pq  # type: ignore
    except Exception as exc:
        head = read_head(path, 4)
        with open(path, "rb") as handle:
            handle.seek(-8, os.SEEK_END)
            tail = handle.read(8)
        footer = int.from_bytes(tail[:4], "little") if len(tail) == 8 else None
        text = (f"magic start: {head!r}; magic end: {tail[4:]!r}; footer bytes: {footer}\n"
                f"pyarrow unavailable: {exc!r}")
        return text, {"magic_ok": head == b"PAR1" and tail[4:] == b"PAR1", "footer_bytes": footer}, \
            "schema unavailable: pyarrow could not be imported"
    try:
        parquet = pq.ParquetFile(path)
        meta = parquet.metadata
        schema = parquet.schema_arrow
        lines = [
            f"rows: {meta.num_rows}",
            f"row groups: {meta.num_row_groups}",
            f"columns: {meta.num_columns}",
            f"format version: {meta.format_version}",
            f"created by: {meta.created_by}",
            f"footer (serialized metadata) bytes: {meta.serialized_size}",
            "",
            "[schema]",
        ]
        columns = []
        for index, item in enumerate(schema):
            lines.append(f"{index:>4} | {item.name} | {item.type} | nullable={item.nullable}")
            columns.append({"name": item.name, "type": str(item.type), "nullable": item.nullable})
        groups = []
        for group_index in range(meta.num_row_groups):
            group = meta.row_group(group_index)
            lines.extend(["", f"[row group {group_index}] rows={group.num_rows} "
                              f"total_byte_size={group.total_byte_size}"])
            group_columns = []
            for column_index in range(group.num_columns):
                column = group.column(column_index)
                stats = column.statistics
                entry = {
                    "column": column.path_in_schema,
                    "physical_type": column.physical_type,
                    "compression": column.compression,
                    "compressed_bytes": column.total_compressed_size,
                    "uncompressed_bytes": column.total_uncompressed_size,
                }
                if stats is not None:
                    try:
                        entry["null_count"] = stats.null_count if stats.has_null_count else None
                        if stats.has_min_max:
                            entry["min"] = _stat_value(stats.min)
                            entry["max"] = _stat_value(stats.max)
                        entry["distinct_count"] = getattr(stats, "distinct_count", None)
                    except Exception as exc:  # some logical types cannot be decoded
                        entry["statistics_error"] = repr(exc)
                group_columns.append(entry)
                lines.append("  " + " | ".join(f"{k}={v}" for k, v in entry.items()))
            groups.append({"rows": group.num_rows, "bytes": group.total_byte_size, "columns": group_columns})
        key_value = {}
        for key, value in (meta.metadata or {}).items():
            key_text = _stat_value(key)
            value_text = _stat_value(value)
            try:
                value_text = json.dumps(json.loads(value_text), ensure_ascii=False, indent=2)
            except Exception:
                pass
            key_value[key_text] = value_text
            lines.extend(["", f"[key-value metadata: {key_text}]", value_text])
        structured = {"rows": meta.num_rows, "row_groups": groups, "columns": columns,
                      "created_by": meta.created_by, "key_value_metadata": key_value}
        return "\n".join(lines), structured, None
    except Exception as exc:
        return None, None, f"Parquet metadata could not be read: {exc!r}"


def archive_listing(path, suffix):
    """Return (text, structured, error) with the member list of an archive."""
    try:
        if zipfile.is_zipfile(path):
            with zipfile.ZipFile(path) as archive:
                members = [
                    {"name": i.filename, "bytes": i.file_size, "compressed": i.compress_size,
                     "crc": f"{i.CRC:08x}", "date": "%04d-%02d-%02d %02d:%02d:%02d" % i.date_time}
                    for i in archive.infolist()
                ]
        elif tarfile.is_tarfile(path):
            with tarfile.open(path) as archive:
                members = [
                    {"name": m.name, "bytes": m.size, "type": "dir" if m.isdir() else "file",
                     "date": datetime.fromtimestamp(m.mtime, timezone.utc).isoformat(timespec="seconds")}
                    for m in archive.getmembers()
                ]
        else:
            return None, None, "not a zip or tar archive"
    except Exception as exc:
        return None, None, f"archive could not be listed: {exc!r}"
    lines = [" | ".join(f"{k}={v}" for k, v in m.items()) for m in members]
    return "\n".join(lines) or "(empty archive)", {"members": members}, None


def binary_metadata(path, *, hash_binaries):
    head = read_head(path, 32)
    info = {"magic_hex": head[:8].hex()}
    if hash_binaries:
        info["sha256"] = sha256_file(path)
    return info


def keys_only_json(text):
    try:
        data = json.loads(text)
    except Exception:
        return "[could not parse; values hidden]"

    def mask(value):
        if isinstance(value, dict):
            return {k: mask(v) for k, v in value.items()}
        if isinstance(value, list):
            return [mask(v) for v in value]
        return "<" + type(value).__name__ + ">"

    return json.dumps(mask(data), ensure_ascii=False, indent=2)


def env_keys_only(text):
    out = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            out.append(line)
            continue
        match = re.match(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_.-]*)\s*=", line)
        out.append(f"{match.group(1)}=<hidden>" if match else "<unparsed line hidden>")
    return "\n".join(out)


