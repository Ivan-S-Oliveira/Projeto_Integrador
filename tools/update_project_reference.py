def decode_text(data):
    """Return (text, encoding) for text content, or (None, reason) for binary.

    Order: UTF-16/UTF-32 with BOM, UTF-8 (with or without BOM), cp1252, latin-1.
    Content with NUL bytes or many control characters is treated as binary.
    """
    for bom, name in (
        (codecs.BOM_UTF32_LE, "utf-32"), (codecs.BOM_UTF32_BE, "utf-32"),
        (codecs.BOM_UTF16_LE, "utf-16"), (codecs.BOM_UTF16_BE, "utf-16"),
    ):
        if data.startswith(bom):
            try:
                return data.decode(name), name
            except UnicodeDecodeError:
                break
    probe = data[:BINARY_PROBE_BYTES]
    if b"\x00" in probe:
        return None, "binary content (NUL bytes)"
    if probe:
        control = sum(1 for b in probe if b < 9 or 13 < b < 32 and b != 27)
        if control / len(probe) > 0.10:
            return None, "binary content (control characters)"
    if data.startswith(codecs.BOM_UTF8):
        try:
            return data[len(codecs.BOM_UTF8):].decode("utf-8"), "utf-8-bom"
        except UnicodeDecodeError:
            pass
    for name in ("utf-8", "cp1252"):
        try:
            return data.decode(name), name
        except UnicodeDecodeError:
            continue
    return data.decode("latin-1"), "latin-1"


def literal_preview(node, max_chars=0):
    try:
        text = repr(ast.literal_eval(node))
    except Exception:
        text = safe_unparse(node, "<dynamic>")
    if not max_chars or len(text) <= max_chars:
        return text
    return text[: max_chars - 3] + "... (full value in the file source)"


def is_generated(posix_path, patterns):
    name = posix_path.rsplit("/", 1)[-1]
    for pattern in patterns:
        if fnmatch.fnmatch(posix_path, pattern) or fnmatch.fnmatch(name, pattern):
            return pattern
    return None


def line_of(text, offset):
    return text.count("\n", 0, offset) + 1


class Redactor:
    """Redacts literal secrets and absolute local paths, logging every change.

    Calling the instance returns (text, events). Each event is a dict with
    `line`, `kind` and `detail`. Values are never logged.
    """

    def __init__(self, root, *, secrets=True, paths=True):
        self.secrets = secrets
        self.paths = paths
        variants = {str(root), root.as_posix(), str(root).replace("\\", "\\\\")}
        self.root_variants = sorted((v for v in variants if v), key=len, reverse=True)
        home = Path.home()
        home_variants = {str(home), home.as_posix(), str(home).replace("\\", "\\\\")}
        self.home_variants = sorted((v for v in home_variants if v), key=len, reverse=True)

    # -- paths -------------------------------------------------------------
    def replace_paths(self, text, events=None):
        if not self.paths:
            return text
        replacements = [(re.escape(v), "<REPO>") for v in self.root_variants]
        replacements += [(re.escape(v), "<HOME>") for v in self.home_variants]
        replacements += [(WINDOWS_USER_RE.pattern, "<HOME>"), (POSIX_HOME_RE.pattern, "<HOME>")]
        for pattern, token in replacements:
            flags = re.IGNORECASE if pattern == WINDOWS_USER_RE.pattern else 0
            compiled = re.compile(pattern, flags)
            if events is not None:
                for match in compiled.finditer(text):
                    events.append({"line": line_of(text, match.start()), "kind": "local-path",
                                   "detail": f"replaced by {token}"})
            text = compiled.sub(token, text)
        return text

    # -- secrets -----------------------------------------------------------
    @staticmethod
    def _secret_key(key):
        spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", key)
        parts = [p for p in re.split(r"[_.\-]+", spaced.lower()) if p]
        if any(p in SECRET_KEY_PARTS for p in parts):
            return True
        return any((a, b) in SECRET_KEY_PAIRS for a, b in zip(parts, parts[1:]))

    def _redact_assignment(self, line, *, python_like):
        match = ASSIGN_RE.match(line)
        if not match or not self._secret_key(match.group("key")):
            return line, False
        value = match.group("value")
        if SAFE_VALUE_RE.match(value):
            return line, False
        quoted = QUOTED_VALUE_RE.match(value)
        if quoted:
            inner = quoted.group("inner")
            if len(inner) < 4 or inner.startswith(("<", "${", "{")) or inner.lower() in {
                "changeme", "change-me", "xxx", "xxxx", "redacted", "none", "null",
            }:
                return line, False
            new_value = quoted.group("q") + "[REDACTED]" + quoted.group("q") + quoted.group("rest")
        else:
            if python_like:
                return line, False  # an unquoted Python value is an expression, not a literal
            bare = value.split(" #", 1)[0].strip()
            if len(bare) < 4:
                return line, False
            new_value = "[REDACTED]"
        return match.group("lead") + match.group("key") + match.group("sep") + new_value, True

    def __call__(self, text, *, mode="prose", skip_secrets=False):
        """mode: `python` (code), `config` (YAML/TOML/INI/JSON/env/shell) or
        `prose` (Markdown, plain text, outputs). Assignment-based redaction is
        applied only to `python` and `config`, to avoid altering prose."""
        python_like = mode == "python"
        events = []
        if self.secrets and not skip_secrets:
            for regex, label in ((PRIVATE_KEY_RE, "private-key"), (GITHUB_TOKEN_RE, "token")):
                for match in regex.finditer(text):
                    events.append({"line": line_of(text, match.start()), "kind": label,
                                   "detail": "literal removed"})
            # Keep the line count, so `path:line` citations stay valid.
            text = PRIVATE_KEY_RE.sub(
                lambda m: "[REDACTED_PRIVATE_KEY]" + "\n" * m.group(0).count("\n"), text
            )
            text = GITHUB_TOKEN_RE.sub("[REDACTED_TOKEN]", text)
            for match in URL_CREDENTIAL_RE.finditer(text):
                events.append({"line": line_of(text, match.start()), "kind": "url-credential",
                               "detail": "password in URL removed"})
            text = URL_CREDENTIAL_RE.sub(r"\1[REDACTED]\3", text)
            lines = text.split("\n") if mode in {"python", "config"} else []
            for index, line in enumerate(lines):
                new_line, changed = self._redact_assignment(line, python_like=python_like)
                if changed:
                    match = ASSIGN_RE.match(line)
                    lines[index] = new_line
                    if match is not None:
                        key = match.group("key")
                        events.append({"line": index + 1, "kind": "secret-assignment",
                                       "detail": f"value of `{key}` removed"})
            if lines:
                text = "\n".join(lines)
        text = self.replace_paths(text, events)
        events.sort(key=lambda e: (e["line"], e["kind"]))
        return text, events


