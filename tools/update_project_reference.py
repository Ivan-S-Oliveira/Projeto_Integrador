def split_document(document, max_bytes):
    """Split on level-2 headings, keeping parts under max_bytes when possible.

    When a section is larger than a part, it is cut between lines. An open code
    block is closed at the end of the part and reopened at the start of the next
    one, after a `### <section> — continuation` header that states the notebook
    cell and the first numbered line, so every part renders and cites correctly.
    """
    chunks = []
    current = []
    for line, inside in iter_lines_with_fence_state(document):
        if not inside and line.startswith("## ") and current:
            chunks.append("".join(current))
            current = []
        current.append(line)
    if current:
        chunks.append("".join(current))

    parts = []
    buffer = []
    buffer_size = 0
    for chunk in chunks:
        chunk_size = len(chunk.encode("utf-8"))
        if buffer and buffer_size + chunk_size > max_bytes:
            parts.append("".join(buffer))
            buffer, buffer_size = [], 0
        if chunk_size <= max_bytes:
            buffer.append(chunk)
            buffer_size += chunk_size
            continue
        lines = chunk.splitlines(keepends=True)
        title = lines[0][3:].strip() if lines and lines[0].startswith("## ") else "section"
        in_fence = None
        opener = ""
        last_cell = None
        for line in lines:
            line_size = len(line.encode("utf-8"))
            if buffer and buffer_size + line_size > max_bytes:
                closing = []
                if not buffer[-1].endswith("\n"):
                    closing.append("\n")
                if in_fence:
                    closing.append(in_fence + "\n")
                closing.append("\n_(continues in the next part)_\n")
                parts.append("".join(buffer + closing))
                context = []
                if last_cell:
                    context.append(f"cell {last_cell}")
                numbered = NUMBERED_LINE_RE.match(line) if in_fence else None
                if numbered:
                    context.append(f"from line {numbered.group(1)}")
                note = f" ({', '.join(context)})" if context else ""
                header = f"{CONTINUATION_MARK}\n### {title} — continuation{note}\n\n"
                buffer = [header]
                buffer_size = len(header.encode("utf-8"))
                if in_fence:
                    buffer.append(opener)
                    buffer_size += len(opener.encode("utf-8"))
            buffer.append(line)
            buffer_size += line_size
            fence = FENCE_RE.match(line)
            if fence:
                if in_fence is None:
                    in_fence = fence.group(1)
                    opener = line if line.endswith("\n") else line + "\n"
                elif line.strip() == in_fence:
                    in_fence = None
            elif in_fence is None:
                cell = CELL_HEADING_RE.match(line)
                if cell:
                    last_cell = cell.group(1)
    if buffer:
        parts.append("".join(buffer))
    return parts


def unbalanced_parts(parts):
    """Numbers of the parts that end inside an open code block."""
    bad = []
    for number, part in enumerate(parts, 1):
        in_fence = None
        for line in part.splitlines():
            fence = FENCE_RE.match(line)
            if not fence:
                continue
            if in_fence is None:
                in_fence = fence.group(1)
            elif line.strip() == in_fence:
                in_fence = None
        if in_fence is not None:
            bad.append(number)
    return bad


def document_anchors(document):
    """Level-2 headings outside code blocks."""
    anchors = set()
    for line, inside in iter_lines_with_fence_state(document):
        if not inside and line.startswith("## "):
            anchors.add(line[3:].strip())
    return anchors


