def write_coverage_csv(path, coverage):
    columns = ["path", "git", "status", "bytes", "modified_utc", "category", "mode", "encoding",
               "lines", "redactions", "gap", "partial", "sha256", "sha256_rendered", "reason"]
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=columns, extrasaction="ignore", lineterminator="\n")
    writer.writeheader()
    for record in sorted(coverage, key=lambda r: r["path"].lower()):
        writer.writerow(record)
    atomic_write(path, buffer.getvalue())


def remove_legacy_outputs(out_dir, keep_parts):
    """Delete outputs of previous versions (v7/v8) and stale parts. Only files
    written by this tool are removed; anything else in those folders is kept."""
    removed = []
    legacy_md = out_dir / LEGACY_MD_NAME
    if legacy_md.is_file():
        legacy_md.unlink()
        removed.append(legacy_md)
    parts_dir = out_dir / PARTS_DIR_NAME
    if parts_dir.is_dir():
        patterns = ["part_*.md", LEGACY_INDEX_NAME] + ([] if keep_parts else ["part_*.txt"])
        for pattern in patterns:
            for old in parts_dir.glob(pattern):
                old.unlink()
                removed.append(old)
    assets_dir = out_dir / LEGACY_ASSETS_DIR_NAME
    if assets_dir.is_dir():
        for old in sorted(assets_dir.rglob("*"), reverse=True):
            if old.is_file():
                old.unlink()
                removed.append(old)
            else:
                old.rmdir()
    for folder in (parts_dir, assets_dir):
        if folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    return removed


def write_txt_parts(parts_dir, text, max_mb):
    """Optional split of the TXT. Code blocks are closed and reopened at every cut."""
    for old in parts_dir.glob("part_*.txt") if parts_dir.is_dir() else ():
        old.unlink()
    parts = split_document(text, int(max_mb * 1024 * 1024))
    total = len(parts)
    written = []
    for index, part in enumerate(parts, 1):
        name = f"part_{index:02d}_of_{total:02d}.txt"
        files = sorted(h for h in document_anchors(part) if h.startswith("`"))
        header = (f"{TXT_MARKER} — part {index}/{total} of {OUTPUT_TXT_NAME} "
                  f"(line numbers in Section 0 refer to the full TXT)\n"
                  f"# Files starting in this part: {len(files)}\n\n")
        target = parts_dir / name
        atomic_write(target, header + part)
        written.append(target)
    return written, parts


def main():
    for stream in (sys.stdout, sys.stderr):
        try:
            reconfigure = getattr(stream, "reconfigure", None)
            if callable(reconfigure):
                reconfigure(encoding="utf-8", errors="replace")  # Windows consoles
        except Exception:
            pass
    args = parse_args()
    if args.split_mb is not None or args.no_split:
        print("[reference] Aviso: --split-mb e --no-split pertencem à v8 e foram ignorados. "
              "A v9 gera um único TXT; use --split-txt-mb N apenas se precisar de partes.", flush=True)
    root = root_dir()
    document, machine, jsonl = build_reference(root, args)
    print("[reference] 7/8 Verificando integridade e gravando o TXT canônico...", flush=True)
    out_dir = root / args.output_dir
    output_txt = out_dir / OUTPUT_TXT_NAME
    output_json = out_dir / OUTPUT_JSON_NAME
    output_jsonl = out_dir / OUTPUT_JSONL_NAME
    output_csv = out_dir / OUTPUT_COVERAGE_NAME
    split = bool(args.split_txt_mb and args.split_txt_mb > 0)

    verification = machine["verification"]
    unbalanced = bool(unbalanced_parts([document]))
    verification["unbalanced_code_blocks"] = unbalanced
    if unbalanced and verification["status"] == "complete":
        verification["status"] = "gaps"
        verification["gaps"] += 1
        verification["gap_paths"].append((OUTPUT_TXT_NAME, "unbalanced code block"))

    text, toc = render_txt(document, machine)
    atomic_write(output_txt, text)
    if output_txt.read_text(encoding="utf-8") != text:
        raise RuntimeError(f"{output_txt} was not written correctly")
    machine["reference_txt"] = {
        "path": f"{args.output_dir.as_posix()}/{OUTPUT_TXT_NAME}",
        "bytes": output_txt.stat().st_size,
        "lines": text.count("\n"),
        "sha256": sha256_text(text),
        "sections": toc,
    }

    print("[reference] 8/8 Gravando artefatos auxiliares e removendo saídas antigas...", flush=True)
    removed = remove_legacy_outputs(out_dir, keep_parts=split)
    written_parts = []
    if split:
        parts_dir = out_dir / PARTS_DIR_NAME
        written_parts, parts = write_txt_parts(parts_dir, text, args.split_txt_mb)
        bad = unbalanced_parts(parts)
        machine["reference_txt"]["parts"] = [p.name for p in written_parts]
        if bad:
            verification["status"] = "gaps"
            verification["gap_paths"].append((PARTS_DIR_NAME, f"unbalanced parts {bad}"))
    if args.json:
        atomic_write(output_json, json.dumps(machine, ensure_ascii=False, indent=2, default=str) + "\n")
    if args.coverage_csv:
        write_coverage_csv(output_csv, machine["coverage"])
    if args.jsonl:
        atomic_write(output_jsonl, "".join(json.dumps(entry, ensure_ascii=False, default=str) + "\n"
                                           for entry in jsonl))
    # A disabled auxiliary output is deleted, so no stale copy from an older run survives.
    for enabled, path in ((args.json, output_json), (args.coverage_csv, output_csv),
                          (args.jsonl, output_jsonl)):
        if not enabled and path.is_file():
            path.unlink()
            removed.append(path)

    attention = machine.get("attention", ())
    high = sum(a.get("severity") == "high" for a in attention)
    print(f"update_project_reference.py schema v{SCHEMA_VERSION}")
    print(f"Reference TXT: {output_txt} ({human_bytes(output_txt.stat().st_size)}, "
          f"{machine['reference_txt']['lines']} lines)  <- use this file as the knowledge base")
    if args.json:
        print(f"Auxiliary:     {output_json} ({human_bytes(output_json.stat().st_size)})")
    if args.jsonl:
        print(f"Auxiliary:     {output_jsonl} ({human_bytes(output_jsonl.stat().st_size)})")
    if args.coverage_csv:
        print(f"Auxiliary:     {output_csv} ({human_bytes(output_csv.stat().st_size)})")
    for part in written_parts:
        print(f"Part:          {part} ({human_bytes(part.stat().st_size)})")
    if removed:
        print(f"Removed {len(removed)} obsolete output file(s) of previous versions.")
    modes = Counter(r["mode"] for r in machine["coverage"])
    print(f"Coverage: {len(machine['coverage'])} files · " + ", ".join(f"{k} {v}" for k, v in sorted(modes.items())))
    print(f"Verification: {verification['status']} · gaps {verification['gaps']} · "
          f"partial {verification['partial']}")
    for path, reason in verification["gap_paths"]:
        print(f"  GAP {path}: {reason}")
    print(f"Python modules: {len(machine.get('python_files', ()))}, notebooks: {len(machine.get('notebooks', ()))}")
    print(f"Attention items: {len(attention)} ({high} high)")
    tests_result = machine.get("tests_result")
    if tests_result:
        print(f"pytest exit code: {tests_result.get('returncode')}")
    if verification["gap_paths"] and not args.allow_gaps:
        print("Coverage verification failed (exit 3). Use --allow-gaps to accept.", flush=True)
        return 3
    if args.fail_on_high and high:
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
