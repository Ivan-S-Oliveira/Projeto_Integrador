def stable_file_id(path, rendered_hash):
    payload = path.replace("\\", "/").encode("utf-8") + b"\0" + rendered_hash.encode("ascii")
    return hashlib.sha256(payload).hexdigest()


def exact_body(text):
    """(body, final_newline): the body written between the markers.

    Exactly one final line break is removed (it is implied by the END marker
    line); every other character, including trailing blank lines, is kept.
    """
    text = text or ""
    if text.endswith("\n"):
        return text[:-1], True
    return text, (text == "")


def verify_verbatim_contract(coverage):
    violations = []
    seen = Counter(r["path"] for r in coverage)
    violations.extend(f"duplicate coverage record: {p}" for p, n in seen.items() if n != 1)
    for r in coverage:
        if not r.get("mandatory_integral"):
            continue
        # keys_only (secrets, local paths) and excluded (outputs of this tool and
        # known reference compilations) are explicit rules registered with a reason.
        if r.get("mode") not in {"full", "extracted", "keys_only", "excluded"}:
            violations.append(f"mandatory file is not integral: {r['path']} ({r.get('mode')})")
        if r.get("mode") in {"full", "extracted"} and not r.get("sha256_rendered"):
            violations.append(f"mandatory file has no rendered hash: {r['path']}")
    return violations


def extract_rendered_bodies(text):
    """path -> exact text between its BEGIN FILE and END OF FILE markers.

    State machine: inside a block only its own END marker ends it, so marker
    lines quoted inside a file can never open or close another block.
    """
    results = {}
    current = None
    end = None
    buffer = []
    for line in text.split("\n"):
        if current is None:
            path = begin_marker_path(line)
            if path is not None:
                current, end, buffer = path, END_OF_FILE.format(path=path), []
            continue
        if line == end:
            results.setdefault(current, "\n".join(buffer))
            current = None
            continue
        buffer.append(line)
    return results


def notebook_cell_sources(body):
    """Inner text of the source block of every cell, in order (outputs ignored)."""
    lines = body.split("\n")
    sources = []
    index = 0
    while index < len(lines):
        if CELL_HEADING_RE.match(lines[index]):
            index += 1
            while index < len(lines) and not FENCE_RE.match(lines[index]):
                index += 1
            if index >= len(lines):
                break
            fence = FENCE_RE.match(lines[index]).group(1)
            start = index + 1
            index = start
            while index < len(lines) and lines[index].strip() != fence:
                index += 1
            sources.append("\n".join(lines[start:index]))
        index += 1
    return sources


def verify_final_txt_round_trip(text, jsonl, line_numbers=False):
    """Re-read the written TXT and prove that every file block is exact.

    1. The TXT has only LF line breaks (grep, wc and splitlines agree).
    2. The text between BEGIN FILE and END OF FILE equals the rendered body.
    3. Text files: the body equals the captured content (one final line break
       removed, see exact_body). Notebooks: every cell source is identical.
    """
    violations = []
    bad = FORBIDDEN_LINE_BREAKS_RE.search(text)
    if bad:
        violations.append(f"TXT contains a forbidden line-break character U+{ord(bad.group(0)):04X}")
    blocks = extract_rendered_bodies(text)
    for path, body in RENDERED_BODIES.items():
        found = blocks.get(path)
        if found is None:
            violations.append(f"missing rendered block: {path}")
        elif found != body:
            violations.append(f"rendered block differs from capture: {path}")
    for record in jsonl:
        path = record["path"]
        if path not in RENDERED_BODIES:
            continue
        if record.get("category") == "notebook":
            cells = record.get("cells") or []
            sources = notebook_cell_sources(RENDERED_BODIES[path])
            if len(sources) != len(cells):
                violations.append(f"notebook cell count differs: {path} ({len(sources)} vs {len(cells)})")
                continue
            for cell, shown in zip(cells, sources):
                expected = "\n".join(split_lines(str(cell.get("source", ""))))
                if shown != expected:
                    violations.append(f"notebook cell source differs: {path}#cell-{cell.get('index')}")
            continue
        if record.get("mode") not in {"full", "extracted", "keys_only"} or "content" not in record:
            continue
        expected, _ = exact_body(normalize_text(str(record["content"])))
        if RENDERED_BODIES[path] != expected:
            violations.append(f"round-trip mismatch: {path}")
    return violations


