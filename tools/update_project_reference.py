def folder_tree(coverage, pruned_dirs=()):
    """Complete folder tree of the repository: every folder and every file, one per line.

    Folders end with '/'. Each file says whether its content is in this TXT.
    """
    tree = {}
    marks = {}
    for record in coverage:
        path = record["path"]
        if path in RENDERED_BODIES:
            mark = ""
        elif record.get("git") == "deleted":
            mark = "  [deleted, not committed yet]"
        elif record.get("mode") == "excluded":
            mark = "  [output of this generator]"
        elif record.get("mode") == "schema":
            mark = "  [data file: schema only, Section 7]"
        else:
            mark = "  [not copied, Section 7]"
        node = tree
        parts = path.split("/")
        for part in parts[:-1]:
            node = node.setdefault(part + "/", {})
        node[parts[-1]] = None
        marks[path] = mark

    lines = ["./"]

    def walk(node, prefix, indent):
        folders = sorted((k for k, v in node.items() if v is not None), key=str.lower)
        files = sorted((k for k, v in node.items() if v is None), key=str.lower)
        for name in folders:
            lines.append("  " * indent + name)
            walk(node[name], prefix + name, indent + 1)
        for name in files:
            lines.append("  " * indent + name + marks.get(prefix + name, ""))

    walk(tree, "", 1)
    if pruned_dirs:
        lines.append("")
        lines.append("Folders not listed (virtual environments, caches, tooling; no project files): "
                     + ", ".join(sorted(pruned_dirs)))
    return lines


def kind_of(record):
    path = record["path"]
    suffix = Path(path).suffix.lower()
    if record.get("mode") == "keys_only":
        return "keys only (values hidden)"
    if suffix in {".py", ".pyi"}:
        return "python test" if is_test_path(path) else "python"
    if suffix == ".ipynb":
        return "notebook (rendered)"
    if suffix in {".yaml", ".yml", ".toml", ".ini", ".cfg"}:
        return "config"
    if suffix in {".json", ".jsonl", ".json5"}:
        return "json"
    if suffix in {".md", ".markdown", ".mdown", ".mkd", ".rst"}:
        return "markdown"
    if Path(path).name.lower() == "requirements.txt":
        return "requirements"
    return suffix.lstrip(".") or Path(path).name


def short_signature(symbol, limit=160):
    text = " ".join(symbol.signature.split()).replace("`", "'")
    return text if len(text) <= limit else text[:limit - 3] + "..."


def module_constants(text):
    """(line, NAME) of the top-level UPPER_CASE assignments of a Python file."""
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return []
    found = []
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        for target in targets:
            if isinstance(target, ast.Name) and target.id.isupper():
                found.append((node.lineno, target.id))
    return found


def outline_lines(symbols, *, notebook=False, constants=()):
    """Metadata lines with every constant, function and class of a file and its line number."""
    if not symbols and not constants:
        return []
    out = ["- Outline (L = line number inside the file, i.e. the N-th line after BEGIN):"]
    if constants:
        out.append("  - Constants: " + ", ".join(f"L{line} `{name}`" for line, name in constants))
    for s in symbols:
        depth = s.qualname.count(".")
        where = f"L{s.lineno}"
        if notebook and "#cell-" in s.path:
            where = f"cell {s.path.rsplit('#cell-', 1)[-1]} L{s.lineno}"
        doc = s.docstring.strip().splitlines()[0][:100] if s.docstring and s.docstring.strip() else ""
        out.append(f"{'  ' * (depth + 1)}- {where} `{short_signature(s)}`" + (f" — {doc}" if doc else ""))
    return out


