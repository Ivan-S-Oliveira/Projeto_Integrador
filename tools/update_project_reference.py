def split_document(document, max_bytes):
    """Split on level-2 headings (outside file blocks), never inside one.

    Every file block (heading, metadata, BEGIN ... END) stays whole in a single
    part; a part can exceed max_bytes only when one block alone is larger.
    """
    chunks = []
    current = []
    for line, inside in iter_structure(document):
        if not inside and line.startswith("## ") and current:
            chunks.append("".join(current))
            current = []
        current.append(line)
    if current:
        chunks.append("".join(current))
    parts = []
    buffer = []
    size = 0
    for chunk in chunks:
        chunk_size = len(chunk.encode("utf-8"))
        if buffer and size + chunk_size > max_bytes:
            parts.append("".join(buffer))
            buffer, size = [], 0
        buffer.append(chunk)
        size += chunk_size
    if buffer:
        parts.append("".join(buffer))
    return parts


def unbalanced_parts(parts):
    """Numbers of the parts that end inside an open file block or code fence."""
    bad = []
    for number, part in enumerate(parts, 1):
        state = list(iter_structure(part))
        if not state:
            continue
        in_block = None
        in_fence = None
        for line, _protected in state:
            bare = line.rstrip("\n")
            if in_block is not None:
                if bare == in_block:
                    in_block = None
                continue
            path = begin_marker_path(bare) if in_fence is None else None
            if path is not None:
                in_block = END_OF_FILE.format(path=path)
                continue
            fence = FENCE_RE.match(bare)
            if fence:
                if in_fence is None:
                    in_fence = fence.group(1)
                elif bare.strip() == in_fence:
                    in_fence = None
        if in_block is not None or in_fence is not None:
            bad.append(number)
    return bad


def document_anchors(document):
    """Level-2 headings outside file blocks and code fences."""
    anchors = set()
    for line, inside in iter_structure(document):
        if not inside and line.startswith("## "):
            anchors.add(line[3:].strip())
    return anchors


def anchor_for(record):
    if record.get("category") == "deleted":
        return f"FILE (deleted from the working tree, content from HEAD): `{record['path']}`"
    return f"FILE: `{record['path']}`"


