def begin_marker_path(line):
    """Path of a BEGIN FILE marker line (exact, column 0), else None."""
    line = line.rstrip("\n")
    if line.startswith(BEGIN_PREFIX) and line.endswith(BEGIN_SUFFIX):
        return line[len(BEGIN_PREFIX):len(line) - len(BEGIN_SUFFIX)]
    return None


def iter_structure(text):
    """Yield (line, protected) for every line (line endings kept).

    protected is True for every line of a file block (from its BEGIN marker to
    its END marker, both included) and for lines inside code fences outside
    file blocks. Headings are only searched where protected is False, so the
    content of a file can never be mistaken for the structure of the TXT.
    """
    in_block = None
    in_fence = None
    for line in text.splitlines(keepends=True):
        bare = line.rstrip("\n")
        if in_block is not None:
            if bare == in_block:
                in_block = None
            yield line, True
            continue
        if in_fence is None:
            path = begin_marker_path(bare)
            if path is not None:
                in_block = END_OF_FILE.format(path=path)
                yield line, True
                continue
        fence = FENCE_RE.match(line)
        if fence:
            if in_fence is None:
                in_fence = fence.group(1)
                yield line, True
                continue
            if line.strip() == in_fence:
                in_fence = None
                yield line, True
                continue
        yield line, in_fence is not None


