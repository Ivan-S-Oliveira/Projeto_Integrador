def heading_lines(text):
    """Level-2 headings outside code blocks -> 1-based line number."""
    found = {}
    for number, (line, inside) in enumerate(iter_lines_with_fence_state(text), 1):
        if not inside and line.startswith("## "):
            found.setdefault(line[3:].strip(), number)
    return found


def end_marker_lines(text):
    """File path -> 1-based line of its END OF FILE marker."""
    prefix, suffix = END_OF_FILE.split("{path}")
    found = {}
    for number, line in enumerate(text.splitlines(), 1):
        if line.startswith(prefix) and line.endswith(suffix):
            found[line[len(prefix):len(line) - len(suffix)]] = number
    return found


def render_txt(document, machine):
    """Final TXT: marker, summary header and Section 0 (table of contents with
    line numbers in this same file), followed by the document body."""
    body_headings = heading_lines(document)
    body_ends = end_marker_lines(document)
    repo = machine.get("repository", {})
    verification = machine.get("verification", {})
    counts = Counter(a.get("severity") for a in machine.get("attention", ()))
    coverage = sorted(machine.get("coverage", ()), key=lambda r: r["path"].lower())
    sections = [h for h in body_headings if not h.startswith("`")]

    def build(offset):
        def at(line):
            return "-" if line is None else str(line + offset)
        section_rows = [[h, at(body_headings[h])] for h in sections]
        file_rows = []
        for r in coverage:
            start = body_headings.get(anchor_for(r))
            file_rows.append([
                f"`{r['path']}`", r.get("mode", ""), r.get("git", ""),
                "-" if r.get("lines") is None else str(r["lines"]),
                at(start), at(body_ends.get(r["path"]) if start is not None else None),
            ])
        header = [
            f"{TXT_MARKER} (schema v{SCHEMA_VERSION})",
            "",
            "> Generated file. Do not edit manually. Single canonical reference of the repository:",
            "> nothing here is duplicated in other generated files that need to be read.",
            "",
            f"- Generated (UTC): `{machine.get('generated_utc')}`",
            f"- Branch / commit: `{repo.get('branch')}` / `{str(repo.get('commit', ''))[:12]}`",
            f"- Files in coverage register: `{len(coverage)}` · verification "
            f"`{verification.get('status', 'n/a')}` (gaps `{verification.get('gaps', 0)}`, "
            f"partial `{verification.get('partial', 0)}`)",
            f"- Attention items: {counts.get('high', 0)} high, {counts.get('medium', 0)} medium, "
            f"{counts.get('low', 0)} low (Section 7)",
            "",
            "## 0. Table of contents",
            "",
            "Line numbers refer to this file. Files without a start line are recorded only in "
            "Sections 19 and 21 (binary, table, excluded or metadata-only).",
            "",
            "### Sections",
            "",
            render_table(["Section", "Starts at line"], section_rows),
            "",
            "### File directory",
            "",
            render_table(["File", "Mode", "Git", "Lines", "Starts at line", "Ends at line"], file_rows),
            "",
            "",
        ]
        return "\n".join(header)

    first = build(0)
    offset = first.count("\n")
    final_header = build(offset)
    assert final_header.count("\n") == offset
    toc = {h: body_headings[h] + offset for h in sections}
    return final_header + document, toc


